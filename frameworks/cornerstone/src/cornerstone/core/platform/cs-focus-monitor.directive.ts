@Directive({ selector: '[csFocusOrigin]' })
export class CsFocusMonitorDirective {
  private readonly monitor = inject(FocusMonitor);
  private readonly element = inject(ElementRef<HTMLElement>);
  readonly origin = output<'keyboard' | 'mouse' | 'touch' | 'program' | null>();
  constructor() {
    this.monitor.monitor(this.element).subscribe((value) => this.origin.emit(value));
  }
}

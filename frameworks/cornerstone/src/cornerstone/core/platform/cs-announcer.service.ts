@Injectable({ providedIn: 'root' })
export class CsAnnouncerService {
  private readonly live = inject(LiveAnnouncer);
  private last = '';
  async announce(message: string, politeness: 'polite' | 'assertive' = 'polite'): Promise<void> {
    if (!message || message === this.last) return;
    this.last = message;
    await this.live.announce(message, politeness);
  }
  clear(): void {
    this.last = '';
    this.live.clear();
  }
}
